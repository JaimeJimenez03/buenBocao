package com.buenbocao.api.common.enums;

/**
 * Tipo de evento culinario.
 */
public enum EventType {
    COOKING_WORKSHOP,    // Taller de cocina
    RECIPE_CHALLENGE,    // Reto de recetas (ej: "mejor tortilla")
    LIVE_COOKING,        // Cocina en directo
    TASTING,             // Degustación
    MEETUP,              // Quedada gastronómica
    COMPETITION,         // Competición de cocina
    MASTERCLASS,         // Masterclass con chef
    SEASONAL             // Evento de temporada (Navidad, Semana Santa...)
}
